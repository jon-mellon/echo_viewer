"""Vendor the browser contract from the actual harvest pipeline, never a rewritten prompt.
Run with harvest_abstracts/classify/.venv/bin/python scripts/sync_paper_pipeline.py HARVEST_ROOT.
"""
import ast
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys

root = Path(sys.argv[1]).resolve()
files = ["classify/src/harvest/classify/prompt.py", "analysis/openai_luna_dag_20.py",
         "analysis/echo_agent_demo/run_agent.py", "analysis/echo_agent_demo/luna_classify.py",
         "analysis/echo_agent_demo/setup_loop.py", "analysis/echo_agent_demo/run_queue.py"]
spec = importlib.util.spec_from_file_location("harvest_browser_prompt", root / files[0])
module = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = module
spec.loader.exec_module(module)

def default_argument(path, flag):
    for node in ast.walk(ast.parse(path.read_text())):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == 'add_argument' and node.args and isinstance(node.args[0], ast.Constant) and node.args[0].value == flag:
            return ast.literal_eval(next(k.value for k in node.keywords if k.arg == 'default'))
    raise ValueError(flag)

runner = root / files[1]
model = default_argument(runner, '--model')
version = default_argument(runner, '--prompt-version')
assert model == default_argument(root / files[5], '--model'), 'Extraction and review defaults differ; define stage routing before syncing'
namespace = {}
for node in ast.parse((root / files[3]).read_text()).body:
    if isinstance(node, (ast.Assign, ast.AugAssign)) and ((isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'SYSTEM' for t in node.targets)) or (isinstance(node, ast.AugAssign) and isinstance(node.target, ast.Name) and node.target.id == 'SYSTEM')):
        exec(compile(ast.Module(body=[node], type_ignores=[]), '<classifier prompt>', 'exec'), namespace)
setup_reasoning = next(ast.literal_eval(value) for node in ast.walk(ast.parse((root / files[4]).read_text())) if isinstance(node, ast.Dict) for key, value in zip(node.keys, node.values) if isinstance(key, ast.Constant) and key.value == 'reasoning' and isinstance(value, ast.Dict))['effort']
classification_reasoning = next(ast.literal_eval(keyword.value) for node in ast.walk(ast.parse((root / files[3]).read_text())) if isinstance(node, ast.Call) for keyword in node.keywords if keyword.arg == 'reasoning_effort')
contract = {
    'model': f'openai/{model}', 'extractionReasoning': default_argument(runner, '--reasoning-effort'),
    'setupReasoning': setup_reasoning, 'classificationReasoning': classification_reasoning, 'promptVersion': version,
    'sourceRevision': subprocess.check_output(['git', '-C', str(root), 'rev-parse', 'HEAD'], text=True).strip(),
    'sourceHashes': {f: hashlib.sha256((root / f).read_bytes()).hexdigest() for f in files},
    'extractionPrompt': getattr(module, f'prompt_system_dag_{version}'),
    'extractionSchema': module.DagConceptExtraction.model_json_schema(by_alias=True),
    'classificationPrompt': namespace['SYSTEM'],
}
out = Path(__file__).resolve().parents[1] / 'site/paper_pipeline_contract.mjs'
generated = '// Generated by scripts/sync_paper_pipeline.py from harvest_abstracts. Do not edit prompts here.\nexport const PAPER_PIPELINE = Object.freeze(' + json.dumps(contract, ensure_ascii=False, indent=2) + ');\n'
if '--check' in sys.argv[2:]:
    assert out.read_text() == generated, 'Browser pipeline contract is stale'
else:
    out.write_text(generated)
print(out)
